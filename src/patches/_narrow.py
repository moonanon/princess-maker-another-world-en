def narrow_rows(ch: str) -> tuple[list[int], int]:
    """(16 row masks, bit 7 = leftmost, width) for a narrow lower-case letter."""
    rows = [0] * 16
    pat = NARROW[ch].split('|')
    for y, r in enumerate(pat):
        rows[4 + y] = sum(0x80 >> x for x, c in enumerate(r) if c == '#')
    return rows, len(pat[0])


