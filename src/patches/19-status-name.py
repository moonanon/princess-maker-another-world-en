def tile(ch: str) -> bytes:
    out = bytearray(16)
    for y, row in enumerate(FONT[ch].split('|')):
        bits = sum(1 << (6 - x) for x, c in enumerate(row) if c == '#')  # column 1-5 of the 8: one pixel of margin
        out[2 * y + 1] = 0  # plane 1 clear: colour 1, as the kana glyphs
        out[2 * y] = bits
    return bytes(out)


def apply(rom: bytearray) -> None:
    spec = importlib.util.spec_from_file_location('vwf', Path(__file__).with_name('15-vwf.py'))
    vwf = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(vwf)
    lst = bytes(rom[snes_to_rom(LIST):snes_to_rom(LIST) + 0x5D])
    if lst[1] != 0x09:  # katakana a
        raise SystemExit(f'${LIST:06X} is not the status box kana list')
    n = 0
    for code, ch in zip(vwf.GRID_CODES, vwf.GRID_LETTERS):
        if ch not in FONT or code not in lst:
            continue
        o = snes_to_rom(GLYPHS) + (lst.index(code) + 0x6A) * 16
        rom[o:o + 16] = tile(ch)
        n += 1
    print(f'  status box name: {n} mini glyphs redrawn as letters')
